update public.books set content_text =
'Хадис 1

От повелителя правоверных Умара ибн аль-Хаттаба (да будет доволен им Аллах): «Поистине, дела оцениваются только по намерениям, и каждому человеку достанется лишь то, что он намеревался обрести».

Пояснение: этот хадис — треть знания. Любое дело начинается с намерения, и награда зависит от того, ради чего человек его совершает.

Хадис 2

«Ислам построен на пяти столпах: свидетельстве, что нет божества, кроме Аллаха, и что Мухаммад — Посланник Аллаха; совершении намаза; выплате закята; хадже и посте в Рамадан».

Пояснение: пять столпов — фундамент религии. Как дом не стоит без опор, так и вера не полна без этих дел.

